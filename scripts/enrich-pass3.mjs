#!/usr/bin/env node
/**
 * Third pass: spend the remaining unauthenticated core quota on individual
 * repository lookups, round-robin across categories so every category has at
 * least some verified metrics instead of only the globally popular ones.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { healthOf, computeCoverage } from './metrics.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'data');
const catalogPath = path.join(DATA, 'catalog.json');
const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));

function api(pathname) {
  try {
    const out = execFileSync('curl', [
      '-sS', '-L', '-k', '--ssl-no-revoke', '--http1.1', '--max-time', '40',
      '-H', 'Accept: application/vnd.github+json',
      '-H', 'User-Agent: awesome-atlas-build',
      '-w', '\n__HTTP__%{http_code}', `https://api.github.com${pathname}`,
    ], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
    const idx = out.lastIndexOf('\n__HTTP__');
    const code = Number(out.slice(idx + 9).trim());
    if (code !== 200) return { ok: false, code, body: out.slice(0, idx) };
    return { ok: true, data: JSON.parse(out.slice(0, idx)) };
  } catch (e) {
    return { ok: false, code: 0, body: String(e.message) };
  }
}

const rate = api('/rate_limit');
const remaining = rate.ok ? rate.data.resources.core.remaining : 0;
const budget = Math.max(0, Math.min(26, remaining - 4));
console.log('core remaining:', remaining, 'budget:', budget);

const missing = catalog.items.filter((it) => it.repo && !it.metrics);
const groups = new Map();
for (const it of missing) {
  if (!groups.has(it.categoryId)) groups.set(it.categoryId, []);
  groups.get(it.categoryId).push(it);
}
for (const arr of groups.values()) {
  arr.sort((a, b) => (b.repo.includes('awesome') ? 1 : 0) - (a.repo.includes('awesome') ? 1 : 0));
}
const queue = [];
const cats = [...groups.values()];
for (let round = 0; round < Math.max(...cats.map((c) => c.length)); round += 1) {
  for (const arr of cats) if (arr[round]) queue.push(arr[round]);
}

const metricIndex = new Map();
for (const it of catalog.items) if (it.repo && it.metrics) metricIndex.set(it.repo.toLowerCase(), it.metrics);
const results = { tried: 0, ok: 0, moved: 0, failed: 0, failures: [] };

for (const it of queue.slice(0, budget)) {
  const key = it.repo.toLowerCase();
  if (metricIndex.has(key)) { it.metrics = metricIndex.get(key); continue; }
  const res = api(`/repos/${it.repo}`);
  results.tried += 1;
  if (res.ok && res.data?.pushed_at) {
    const m = healthOf({ ...res.data, __via: 'github-repo' });
    if (res.data.full_name?.toLowerCase() !== key) { m.canonicalRepo = res.data.full_name; results.moved += 1; }
    it.metrics = m;
    metricIndex.set(key, m);
    for (const other of catalog.items) {
      if (other !== it && other.repo?.toLowerCase() === key && !other.metrics) other.metrics = m;
    }
    results.ok += 1;
  } else {
    results.failed += 1;
    if (results.failures.length < 8) results.failures.push({ repo: it.repo, code: res.code, body: res.body.slice(0, 100) });
  }
}

const coverage = computeCoverage(catalog);
catalog.enrichment = {
  ...catalog.enrichment,
  fetchedAt: new Date().toISOString(),
  method: 'GitHub REST: star-range repository search + individual repo lookups (unauthenticated quota, round-robin by category)',
  coverage: { ...coverage, searchPool: catalog.enrichment?.coverage?.searchPool ?? null },
};
const upstreamPath = path.join(DATA, 'upstream.json');
const upstream = fs.existsSync(upstreamPath) ? JSON.parse(fs.readFileSync(upstreamPath, 'utf8')) : { commits: [] };
upstream.coverage = coverage;
fs.writeFileSync(upstreamPath, JSON.stringify(upstream, null, 2));
fs.writeFileSync(catalogPath, JSON.stringify(catalog, null, 2));
fs.writeFileSync(
  path.join(DATA, 'catalog.js'),
  `/* Generated by scripts/build-data.mjs + enrich.mjs + enrich-pass2.mjs + enrich-pass3.mjs - do not edit by hand. */\nwindow.__ATLAS_DATA__ = ${JSON.stringify(catalog)};\nwindow.__ATLAS_UPSTREAM__ = ${JSON.stringify(upstream)};\n`,
);
fs.writeFileSync(path.join(DATA, 'enrich-pass3-report.json'), JSON.stringify({ coverage, results, budget }, null, 2));
console.log(JSON.stringify({ coverage, results }, null, 2));
