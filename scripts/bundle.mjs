#!/usr/bin/env node
/**
 * Assemble the single data/catalog.js payload consumed by the static site.
 * Keeps JSON files as the source of truth so validation can re-check them.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'data');
const read = (f) => JSON.parse(fs.readFileSync(path.join(DATA, f), 'utf8'));

const catalog = read('catalog.json');
const upstream = read('upstream.json');
const history = read('history.json');
const i18n = read('i18n.json');

const parts = [
  '/* Generated by scripts/bundle.mjs - do not edit by hand. */',
  `window.__ATLAS_DATA__ = ${JSON.stringify(catalog)};`,
  `window.__ATLAS_UPSTREAM__ = ${JSON.stringify(upstream)};`,
  `window.__ATLAS_HISTORY__ = ${JSON.stringify(history)};`,
  `window.__ATLAS_I18N__ = ${JSON.stringify(i18n)};`,
  '',
];
const out = parts.join('\n');
fs.writeFileSync(path.join(DATA, 'catalog.js'), out);

console.log(JSON.stringify({
  file: 'data/catalog.js',
  bytes: Buffer.byteLength(out, 'utf8'),
  items: catalog.items.length,
  enriched: catalog.items.filter((i) => i.metrics).length,
  descriptions: Object.keys(i18n.descriptions).length,
  hints: Object.keys(i18n.hints).length,
  historyRevisions: history.snapshots.length,
}, null, 2));
